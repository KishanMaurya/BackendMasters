/** Which tab a key moves to, following the WAI-ARIA tabs pattern. Null means the key isn't ours. */
export function tabIndexForKey(key: string, current: number, count: number): number | null {
  switch (key) {
    case 'ArrowRight':
      return (current + 1) % count;
    case 'ArrowLeft':
      return (current - 1 + count) % count;
    case 'Home':
      return 0;
    case 'End':
      return count - 1;
    default:
      return null;
  }
}
